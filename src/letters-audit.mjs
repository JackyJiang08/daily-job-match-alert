// Letter overwrite audit (2026-11-09, read only). Before letters were stored by job ID, a second posting of the same
// company on the same report date was saved into the first one's company folder and replaced its letter. This
// finds the postings that lost a letter that way: a letter candidate of a report date with no letter of its own,
// whose company folder on that date holds another posting's letter. Evidence per date: how many letters the
// automatic pass of that date says it generated against how many automatic letters created during that pass are
// still on disk (the shortfall), and Reach Out texts written with a letter for the posting. Nothing is written or
// regenerated.
import { sanitizeCompany } from './cover-letter/compose.mjs';

function slugs(...names) {
  return new Set(names.filter(Boolean).map(name => sanitizeCompany(name)).filter(Boolean));
}

// letters: the store's listLetters(); days: [{ date, matches, autoLetters (payload meta) }]; outreachJobs: the Reach
// Out state's jobs ({ jobId: { messages: { source } } }); jobIdOf, companyFor (letterCompanyFor), isCandidate.
export function auditLetterOverwrites({ letters = [], days = [], outreachJobs = {}, jobIdOf, companyFor, isCandidate = () => true }) {
  const byJob = new Set(letters.map(letter => letter.jobId).filter(Boolean));
  const rows = [];
  const passes = [];
  for (const day of days) {
    const pass = day.autoLetters || null;
    let shortfall = null;
    if (pass?.startedAt && Number(pass.generated) > 0) {
      const from = Date.parse(pass.startedAt);
      const to = Date.parse(pass.finishedAt || pass.startedAt) + 60_000;
      const kept = letters.filter(letter => letter.source === 'auto' && Date.parse(letter.createdAt || '') >= from && Date.parse(letter.createdAt || '') <= to).length;
      shortfall = Math.max(0, Number(pass.generated) - kept);
      passes.push({ date: day.date, generated: Number(pass.generated), kept, shortfall, startedAt: pass.startedAt });
    }
    const folders = letters.filter(letter => letter.date === day.date);
    const found = [];
    for (const job of day.matches || []) {
      const id = jobIdOf(job);
      const fromLetter = outreachJobs[id]?.messages?.source === 'letter';
      if (byJob.has(id) || !(isCandidate(job) || fromLetter)) continue;
      const company = companyFor(job)?.name || job.company || '';
      const names = slugs(company, job.company);
      // Only company folders replaced letters; a job ID folder (2026-11-09 on) holds its own posting's letter only.
      const holder = folders.find(letter => letter.jobId !== id && letter.slug !== letter.jobId && [...slugs(letter.company, letter.fullName, letter.companySlug, letter.slug)].some(slug => names.has(slug)));
      if (!holder) continue;
      found.push({ date: day.date, jobId: id, title: job.title || '', company, url: job.url || '', folder: holder.slug, keptJobId: holder.jobId || null, keptTitle: holder.jobTitle || '', keptSource: holder.source || null, keptCreatedAt: holder.createdAt || null, reachOutFromLetter: fromLetter });
    }
    for (const row of found) {
      row.evidence = row.reachOutFromLetter ? 'confirmed' : shortfall != null && shortfall >= found.length ? 'likely' : shortfall ? 'possible' : 'unproven';
      row.dateShortfall = shortfall;
      rows.push(row);
    }
  }
  return { rows, passes };
}

export function auditMarkdown({ rows, passes }) {
  const line = cells => `| ${cells.map(cell => String(cell ?? '').replace(/\|/g, '/')).join(' | ')} |`;
  const out = ['# Letter overwrite audit (read only)', '',
    'Postings with no letter of their own whose company folder on the same date holds another posting\'s letter. Evidence: confirmed (Reach Out texts were written with a letter for this posting), likely (the automatic pass of that date generated more letters than are left, at least one per posting listed), possible (a shortfall smaller than the list), unproven (no shortfall recorded; the second letter may never have been written).', ''];
  if (!rows.length) out.push('No overwritten letters found.');
  else {
    out.push(line(['Date', 'Posting (no letter)', 'Job ID', 'Folder now holds', 'Held Job ID', 'Evidence']), line(['---', '---', '---', '---', '---', '---']));
    for (const row of rows) out.push(line([row.date, `${row.company} · ${row.title}`, row.jobId, `${row.folder} (${row.keptTitle || 'unknown title'})`, row.keptJobId, row.evidence]));
  }
  const short = passes.filter(pass => pass.shortfall > 0);
  if (short.length) {
    out.push('', '## Automatic passes with letters missing', '', 'Letters each pass generated, the automatic letters created during it that are still on disk, and the postings listed above for that date. A shortfall can also come from a letter regenerated by hand later.', '',
      line(['Date', 'Generated', 'Left', 'Shortfall', 'Listed']), line(['---', '---', '---', '---', '---']));
    for (const pass of short) out.push(line([pass.date, pass.generated, pass.kept, pass.shortfall, rows.filter(row => row.date === pass.date).length]));
  } else out.push('', 'Every automatic pass on record still has all the letters it generated.');
  out.push('', `Total: ${rows.length} posting(s) listed (${['confirmed', 'likely', 'possible', 'unproven'].map(level => `${rows.filter(row => row.evidence === level).length} ${level}`).join(', ')}).`);
  return `${out.join('\n')}\n`;
}
